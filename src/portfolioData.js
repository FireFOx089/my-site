export const STORAGE_ITEMS_KEY = 'artsnfar_portfolio_items';
export const STORAGE_FILTERS_KEY = 'artsnfar_portfolio_filters';

export function loadPortfolioItems() {
  try {
    const raw = localStorage.getItem(STORAGE_ITEMS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Could not load portfolio items from localStorage:', err);
  }
  return DEFAULT_PORTFOLIO_ITEMS;
}

export function savePortfolioItems(items) {
  try {
    localStorage.setItem(STORAGE_ITEMS_KEY, JSON.stringify(items));
    window.dispatchEvent(new CustomEvent('artsnfar_data_updated', { detail: { type: 'items', items } }));
  } catch (err) {
    console.error('Failed to save portfolio items to localStorage:', err);
  }
}

export function loadFilters() {
  try {
    const raw = localStorage.getItem(STORAGE_FILTERS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Could not load filters from localStorage:', err);
  }
  return DEFAULT_FILTERS;
}

export function saveFilters(filters) {
  try {
    localStorage.setItem(STORAGE_FILTERS_KEY, JSON.stringify(filters));
    window.dispatchEvent(new CustomEvent('artsnfar_data_updated', { detail: { type: 'filters', filters } }));
  } catch (err) {
    console.error('Failed to save filters to localStorage:', err);
  }
}

export function resetPortfolioData() {
  try {
    localStorage.removeItem(STORAGE_ITEMS_KEY);
    localStorage.removeItem(STORAGE_FILTERS_KEY);
    window.dispatchEvent(new CustomEvent('artsnfar_data_updated', { detail: { type: 'reset' } }));
  } catch (err) {
    console.error('Failed to reset portfolio data:', err);
  }
}

export function exportPortfolioCode(items, filters) {
  return `// Paste this array directly into portfolioData.js to make changes permanent:
export const DEFAULT_FILTERS = ${JSON.stringify(filters, null, 2)};

export const DEFAULT_PORTFOLIO_ITEMS = ${JSON.stringify(items, null, 2)};
`;
}
